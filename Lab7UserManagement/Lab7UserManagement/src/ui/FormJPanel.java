    /**
     * Checks a user's data before it is saved.
     *
     * @return an error message, or null if everything is valid
     */
    static String validateUser(User u) {
        if (u.getFirstName().isEmpty() || u.getLastName().isEmpty()) {
            return "First name and last name are required.";
        }
        if (!u.getFirstName().matches("[A-Za-z ]{2,50}") || !u.getLastName().matches("[A-Za-z ]{2,50}")) {
            return "Names must be 2-50 letters (spaces allowed).";
        }
        if (u.getGender() == null) {
            return "Please select a gender.";
        }
        if (u.getDob() == null) {
            return "Please select a date of birth.";
        }
        if (u.getDob().isAfter(LocalDate.now())) {
            return "Date of birth cannot be in the future.";
        }
        if (u.getAge() < 1 || u.getAge() > 120) {
            return "Please select a valid date of birth (age 1-120).";
        }
        if (!u.getPhone().matches("\\d{3}-\\d{3}-\\d{4}")) {
            return "Please enter a 10-digit phone number (617-555-0123).";
        }
        if (!u.getEmail().matches("^[\\w.+-]+@[\\w-]+\\.[\\w.]+$")) {
            return "Please enter a valid email address.";
        }
        if (u.getContinent() == null) {
            return "Please select a continent.";
        }
        return null;
    }

    /** The age for a date of birth, as text (empty if no date). */
    static String ageText(Date dob) {
        LocalDate d = toLocalDate(dob);
        return d == null || d.isAfter(LocalDate.now()) ? "" : String.valueOf(Period.between(d, LocalDate.now()).getYears());
    }

    /** Converts the JDateChooser's date to a LocalDate (null stays null). */
    static LocalDate toLocalDate(Date date) {
        return date == null ? null : date.toInstant().atZone(ZoneId.systemDefault()).toLocalDate();
    }

    /** Opens a file browser for an image and returns its path (null if cancelled). */
    static String choosePhoto(Component parent) {
        JFileChooser chooser = new JFileChooser();
        chooser.setFileFilter(new FileNameExtensionFilter("Images (jpg, png, gif)", "jpg", "jpeg", "png", "gif"));
        if (chooser.showOpenDialog(parent) == JFileChooser.APPROVE_OPTION) {
            return chooser.getSelectedFile().getAbsolutePath();
        }
        return null;
    }

    /** Loads the photo scaled to a square of the given size (null if there is no photo). */
    static ImageIcon scaledPhoto(String path, int size) {
        if (path == null || path.isBlank() || !new File(path).exists()) {
            return null;
        }
        Image img = new ImageIcon(path).getImage().getScaledInstance(size, size, Image.SCALE_SMOOTH);
        return new ImageIcon(img);
    }

