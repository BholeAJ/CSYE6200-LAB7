    private void btnSubmitActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSubmitActionPerformed
        User user = new User();
        user.setFirstName(txtFirstName.getText().trim());
        user.setLastName(txtLastName.getText().trim());
        user.setGender(rdoMale.isSelected() ? "Male" : rdoFemale.isSelected() ? "Female" : null);
        user.setDob(toLocalDate(dcDob.getDate()));
        user.setAge(user.getDob() == null ? 0 : Period.between(user.getDob(), LocalDate.now()).getYears());
        user.setPhone(ftxtPhone.getText().trim());
        user.setEmail(txtEmail.getText().trim());
        user.setContinent(cmbContinent.getSelectedIndex() > 0 ? (String) cmbContinent.getSelectedItem() : null);
        user.setExperience(txtExperience.getText().trim());
        user.setHobbies(txtHobbies.getText().trim());
        user.setPhotoPath(photoPath);

        String error = validateUser(user);
        if (error != null) {
            JOptionPane.showMessageDialog(this, error, "Input Error", JOptionPane.WARNING_MESSAGE);
            return;
        }
        try {
            DatabaseConnector.addUser(user);
            JOptionPane.showMessageDialog(this, user.toString(), "Success - user saved to the database",
                    JOptionPane.INFORMATION_MESSAGE, scaledPhoto(user.getPhotoPath(), 150));
            clearFields();
        } catch (SQLException ex) {
            if (DatabaseConnector.isDuplicateEmail(ex)) {
                JOptionPane.showMessageDialog(this, "That email is already registered. Please use a different email.",
                        "Input Error", JOptionPane.ERROR_MESSAGE);
            } else {
                JOptionPane.showMessageDialog(this, "Database error: " + ex.getMessage(),
                        "Error", JOptionPane.ERROR_MESSAGE);
            }
        }
    }//GEN-LAST:event_btnSubmitActionPerformed

