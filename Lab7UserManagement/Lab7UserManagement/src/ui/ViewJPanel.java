    // EDIT unlocks the fields. While editing the button says CANCEL, which puts the old values back.
    private void btnEditActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEditActionPerformed
        if (selectedUser == null) {
            return;
        }
        if (editing) {
            showUser(selectedUser); // undo any changes
            editing = false;
        } else {
            editing = true;
        }
        setFieldsEnabled(editing);
        updateButtons();
    }//GEN-LAST:event_btnEditActionPerformed

    // UPDATE: save the changed fields to the database
    private void btnUpdateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnUpdateActionPerformed
        if (selectedUser == null || !editing) {
            return;
        }
        User edited = new User();
        edited.setId(selectedUser.getId());
        edited.setFirstName(txtFirstName.getText().trim());
        edited.setLastName(txtLastName.getText().trim());
        edited.setGender(rdoMale.isSelected() ? "Male" : rdoFemale.isSelected() ? "Female" : null);
        edited.setDob(FormJPanel.toLocalDate(dcDob.getDate()));
        edited.setAge(edited.getDob() == null ? 0 : Period.between(edited.getDob(), LocalDate.now()).getYears());
        edited.setPhone(ftxtPhone.getText().trim());
        edited.setEmail(txtEmail.getText().trim());
        edited.setContinent(cmbContinent.getSelectedIndex() > 0 ? (String) cmbContinent.getSelectedItem() : null);
        edited.setExperience(txtExperience.getText().trim());
        edited.setHobbies(txtHobbies.getText().trim());
        edited.setPhotoPath(photoPath);

        String error = FormJPanel.validateUser(edited);
        if (error != null) {
            JOptionPane.showMessageDialog(this, error, "Input Error", JOptionPane.WARNING_MESSAGE);
            return;
        }
        try {
            DatabaseConnector.editUser(edited);
            JOptionPane.showMessageDialog(this, edited.toString(), "Success - user updated",
                    JOptionPane.INFORMATION_MESSAGE, FormJPanel.scaledPhoto(edited.getPhotoPath(), 150));
            populateTable();
            selectRowById(edited.getId()); // keep the same user selected
        } catch (SQLException ex) {
            if (DatabaseConnector.isDuplicateEmail(ex)) {
                JOptionPane.showMessageDialog(this, "That email is already registered to another user.",
                        "Input Error", JOptionPane.ERROR_MESSAGE);
            } else {
                showError(ex);
            }
        }
    }//GEN-LAST:event_btnUpdateActionPerformed

    // DELETE: remove the selected user from the database
    private void btnDeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeleteActionPerformed
        if (selectedUser == null || editing) {
            return;
        }
        int choice = JOptionPane.showConfirmDialog(this,
                "Delete " + selectedUser.getFirstName() + " " + selectedUser.getLastName() + "?",
                "Confirm Delete", JOptionPane.YES_NO_OPTION, JOptionPane.WARNING_MESSAGE);
        if (choice != JOptionPane.YES_OPTION) {
            return;
        }
        try {
            DatabaseConnector.deleteUser(selectedUser.getId());
            JOptionPane.showMessageDialog(this, "User deleted.");
            populateTable();
        } catch (SQLException ex) {
            showError(ex);
        }
    }//GEN-LAST:event_btnDeleteActionPerformed

    private void btnChangePhotoActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnChangePhotoActionPerformed
        String path = FormJPanel.choosePhoto(this);
        if (path != null) {
            photoPath = path;
            showPhoto();
        }
    }//GEN-LAST:event_btnChangePhotoActionPerformed

    // READ: load every row from the database into the JTable
    private void populateTable() {
        try {
            users = DatabaseConnector.getAllUsers();
        } catch (SQLException ex) {
            users = new ArrayList<>();
            showError(ex);
        }
        DefaultTableModel model = (DefaultTableModel) tblUsers.getModel();
        model.setRowCount(0);
        for (User u : users) {
            model.addRow(new Object[]{u.getId(), u.getFirstName(), u.getLastName(),
                u.getAge(), u.getEmail(), u.getContinent()});
        }
    }

    /** Selects the table row of the user with this id (used after Update). */
    private void selectRowById(int id) {
        for (int i = 0; i < users.size(); i++) {
            if (users.get(i).getId() == id) {
                tblUsers.setRowSelectionInterval(i, i);
                tblUsers.scrollRectToVisible(tblUsers.getCellRect(i, 0, true));
                return;
            }
        }
    }

    // When a row is clicked, show that user's details on the left (read-only)
    private void onRowSelected() {
        int row = tblUsers.getSelectedRow();
        editing = false;
        if (row < 0) {
            selectedUser = null;
            clearFields();
        } else {
            selectedUser = users.get(row);
            showUser(selectedUser);
        }
        setFieldsEnabled(false);
        updateButtons();
    }

    /** Shows a user's values in the fields. */
    private void showUser(User u) {
        txtFirstName.setText(u.getFirstName());
        txtLastName.setText(u.getLastName());
        rdoFemale.setSelected("Female".equalsIgnoreCase(u.getGender()));
        rdoMale.setSelected(!"Female".equalsIgnoreCase(u.getGender()));
        dcDob.setDate(u.getDob() == null ? null
                : Date.from(u.getDob().atStartOfDay(ZoneId.systemDefault()).toInstant()));
        txtAge.setText(String.valueOf(u.getAge()));
        ftxtPhone.setText(u.getPhone());
        txtEmail.setText(u.getEmail());
        cmbContinent.setSelectedItem(u.getContinent());
        txtExperience.setText(u.getExperience());
        txtHobbies.setText(u.getHobbies());
        photoPath = u.getPhotoPath() == null ? "" : u.getPhotoPath();
        showPhoto();
    }

    private void clearFields() {
        txtFirstName.setText("");
        txtLastName.setText("");
        genderGroup.clearSelection();
        dcDob.setDate(null);
        txtAge.setText("");
        ftxtPhone.setValue(null);
        txtEmail.setText("");
        cmbContinent.setSelectedIndex(0);
        txtExperience.setText("");
        txtHobbies.setText("");
        photoPath = "";
        showPhoto();
    }

    private void showPhoto() {
        javax.swing.ImageIcon icon = FormJPanel.scaledPhoto(photoPath, 110);
        lblPhotoPreview.setIcon(icon);
        lblPhotoPreview.setText(icon == null ? "No photo" : "");
    }

    /** Enables or disables every input (the age is always calculated, so it stays read-only). */
    private void setFieldsEnabled(boolean enabled) {
        JComponent[] inputs = {txtFirstName, txtLastName, rdoMale, rdoFemale, dcDob, ftxtPhone, txtEmail,
            cmbContinent, txtExperience, txtHobbies, btnChangePhoto};
        for (JComponent c : inputs) {
            c.setEnabled(enabled);
        }
    }

    /** Turns the buttons on/off to match what the user is doing right now. */
    private void updateButtons() {
        boolean rowSelected = selectedUser != null;
        btnEdit.setText(editing ? "Cancel" : "Edit");
        btnEdit.setEnabled(rowSelected);
        btnUpdate.setEnabled(rowSelected && editing);
        btnDelete.setEnabled(rowSelected && !editing);
    }

    private void showError(Exception ex) {
        JOptionPane.showMessageDialog(this, "Error: " + ex.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
    }

